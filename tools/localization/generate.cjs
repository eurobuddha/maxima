for (const [name, contents] of outputs) {
  const file = path.join(root, name);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== contents) throw Error('Outdated translations: ' + name);
  } else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, contents); }
}
// The iOS app is a sibling repository. Sync only when its explicit root is supplied.
const iosIndex = process.argv.indexOf('--ios-root');
if (iosIndex !== -1) {
  if (!process.argv[iosIndex + 1]) throw Error('--ios-root requires the existing iOS repository path');
  const iosRoot = path.resolve(process.argv[iosIndex + 1]);
  if (!fs.existsSync(path.join(iosRoot, 'App/project.yml'))) throw Error('Not a Parlons iOS repository: ' + iosRoot);
  for (const [name, contents] of outputs) {
    if (!name.startsWith('localization/ios/')) continue;
    const target = path.join(iosRoot, 'App/Resources', name.slice('localization/ios/'.length));
    if (process.argv.includes('--check')) {
      if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== contents) throw Error('Outdated iOS translations: ' + target);
    } else {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, contents);
    }
  }
}
